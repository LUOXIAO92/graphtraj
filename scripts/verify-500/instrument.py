"""Task 500: instrument one DIAGNOSTIC clone (never src/, never a commit): who ends the host test's survivor.

    python -I instrument.py <clone dir (holds src/ and venv/)> <kill-log dir>

1. ``verify500_hook.py`` and ``zz_verify500.pth`` go into the clone venv's purelib. A ``.pth`` (not a
   sitecustomize: miniconda's stdlib ``sitecustomize.py`` comes first on sys.path) runs in every process of
   that venv's Python: pytest, the host processes (``sys.executable``), the survivors, Workers. Not in a nested
   venv built on the base Python, nor under ``-S``. The hook (sys.addaudithook) appends one JSON line per
   ``os.kill``/``os.killpg`` with a signal other than 0 (time, sender pid/ppid/argv, target, signal, short
   stack), and per ``subprocess.Popen``/``os.system``/``os.posix_spawn``/``os.exec`` whose arguments name
   kill, pkill or killall, to ``<kill-log>/<pid>.jsonl``. It never sends a signal and never prints.
   In the survivor itself (argv ``-c 'import time; time.sleep(120)'``) it also records its start, a heartbeat
   file (time and ppid every 0.1 s), every catchable terminating signal it receives (logged, then the default
   action) and a normal interpreter exit. SIGKILL cannot be caught: no sender line, no signal line and no
   exit line together mean SIGKILL from a non-Python sender or the kernel.
2. The clone's copy of tests/test_claude_codex_host_shutdown.py gets a watcher: right after each test reads its
   survivors' pids, a daemon thread per pid polls ``kill(pid, 0)`` every 10 ms and writes when it is first
   found gone (``<kill-log>/survivors-<pytest pid>.jsonl``). The test's assertions are unchanged.
Idempotent. Exit 1 when an anchor of the patch is missing (the test changed: update this script).
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

TAG = '# --- Task 500 diagnostic watcher (scripts/verify-500/instrument.py; diagnostic clone only) ---'
ANCHOR = "        survivors = first.facts['survivors']\n"

HOOK = r'''"""Task 500 diagnostic audit hook (generated by scripts/verify-500/instrument.py). Logs only; never signals."""
import json, os, re, signal, sys, threading, time, traceback

LOG = LOG_DIR
SURVIVOR = list(sys.orig_argv[-2:]) == ['-c', 'import time; time.sleep(120)']
KILLS = re.compile(r'(^|[\s/;&|(])(kill|pkill|killall)(\s|$)')


def write(kind, **fields):
    try:
        record = {'t': time.time(), 'kind': kind, 'pid': os.getpid(), 'ppid': os.getppid(),
                  'argv': [str(item)[:160] for item in sys.orig_argv[:6]],
                  'test': os.environ.get('PYTEST_CURRENT_TEST', ''), **fields}
        line = (json.dumps(record, default=str) + '\n').encode()
        fd = os.open(os.path.join(LOG, f'{os.getpid()}.jsonl'), os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o644)
        try:
            os.write(fd, line)
        finally:
            os.close(fd)
    except Exception:
        pass


def stack():
    return [line.strip() for line in traceback.format_stack(limit=10)[:-2]]


def names_kill(arguments):
    try:
        if isinstance(arguments, (str, bytes)):
            arguments = [arguments]
        return any(KILLS.search(os.fsdecode(item)) for item in arguments or [])
    except Exception:
        return False


def hook(event, arguments):
    try:
        if event in ('os.kill', 'os.killpg'):
            target, sig = arguments
            if int(sig) != 0:
                write(event, target=int(target), sig=int(sig), stack=stack())
        elif event == 'subprocess.Popen' and names_kill(arguments[1]):
            write(event, command=str(arguments[1])[:400], stack=stack())
        elif event in ('os.system', 'os.posix_spawn', 'os.exec') and names_kill(arguments[0] if event == 'os.system' else arguments[1]):
            write(event, command=str(arguments[:2])[:400], stack=stack())
    except Exception:
        pass


sys.addaudithook(hook)

if SURVIVOR:
    write('survivor-start')

    def beat():
        path = os.path.join(LOG, f'hb-{os.getpid()}')
        while True:
            try:
                fd = os.open(path, os.O_WRONLY | os.O_CREAT, 0o644)
                try:
                    os.pwrite(fd, f'{time.time():.3f} {os.getppid():>8}\n'.encode(), 0)
                finally:
                    os.close(fd)
            except Exception:
                pass
            time.sleep(0.1)

    threading.Thread(target=beat, daemon=True).start()

    def received(signum, frame):
        write('survivor-signal', sig=signum)
        signal.signal(signum, signal.SIG_DFL)
        os.kill(os.getpid(), signum)

    for name in ('SIGTERM', 'SIGHUP', 'SIGINT', 'SIGQUIT', 'SIGUSR1', 'SIGUSR2', 'SIGALRM', 'SIGXCPU', 'SIGVTALRM',
                 'SIGPROF'):
        try:
            signal.signal(getattr(signal, name), received)
        except Exception:
            pass
    import atexit
    atexit.register(lambda: write('survivor-exit'))
'''

WATCHER = '''

TAG
def _verify500_watch(pids):
    """Record when each survivor is first found gone (pid no longer resolves)."""
    import json as _json, os as _os, threading as _threading, time as _time
    test, log = _os.environ.get('PYTEST_CURRENT_TEST', ''), LOG_FILE % _os.getpid()

    def write(**record):
        with open(log, 'a') as stream:
            stream.write(_json.dumps({'t': _time.time(), 'test': test, 'watcher': _os.getpid(), **record}) + '\\n')

    def watch(pid):
        write(event='watch', pid=pid)
        deadline = _time.monotonic() + 150
        while _time.monotonic() < deadline:
            try:
                _os.kill(pid, 0)
            except ProcessLookupError:
                write(event='gone', pid=pid)
                return
            except PermissionError:
                pass
            _time.sleep(0.01)
        write(event='still-there-after-150s', pid=pid)

    for pid in pids:
        _threading.Thread(target=watch, args=(pid,), daemon=True).start()
'''


def main(clone: Path, logs: Path) -> int:
    logs.mkdir(parents=True, exist_ok=True)
    # Each run points ``current`` at its own empty directory (steps.zsh fresh_log); unset, nothing is written.
    current = logs.resolve() / 'current'
    purelib = Path(subprocess.run([str(clone / 'venv/bin/python'), '-I', '-c',
                                   'import sysconfig; print(sysconfig.get_paths()["purelib"])'],
                                  check=True, capture_output=True, text=True).stdout.strip())
    (purelib / 'verify500_hook.py').write_text(HOOK.replace('LOG_DIR', repr(str(current))))
    (purelib / 'zz_verify500.pth').write_text('import verify500_hook\n')
    print(f'hook: {purelib}/verify500_hook.py (+ zz_verify500.pth); kill log {current} (-> runs/<run>)')

    test = clone / 'src/tests/test_claude_codex_host_shutdown.py'
    text = test.read_text()
    if TAG not in text:
        if text.count(ANCHOR) != 2:
            print(f'STOP: expected 2 survivor anchors in {test}, found {text.count(ANCHOR)}')
            return 1
        text = text.replace(ANCHOR, ANCHOR + "        _verify500_watch(survivors)\n")
        text += WATCHER.replace('TAG', TAG).replace('LOG_FILE', repr(str(current / 'survivors-%d.jsonl')))
        test.write_text(text)
    print(f'watcher: {test} ({text.count("_verify500_watch(survivors)")} call sites)')
    check = subprocess.run([str(clone / 'venv/bin/python'), '-I', '-c',
                            'import sys, verify500_hook; print("hook active:", verify500_hook.LOG)'],
                           capture_output=True, text=True)
    print(check.stdout.strip() or check.stderr.strip())
    return 0 if check.returncode == 0 else 1


if __name__ == '__main__':
    sys.exit(main(Path(sys.argv[1]), Path(sys.argv[2])))
